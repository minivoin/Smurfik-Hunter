package com.papasmurf.detect;

/**
 * Веса сигналов схожести двух аккаунтов.
 *
 * Сумма весов реализованных сигналов равна 1.0, а итоговый скор всё равно
 * делится на эту сумму (см. {@link PairFeatures#total(Weights)}). Деление
 * оставлено намеренно: при добавлении новых сигналов шкала останется в
 * диапазоне 0..1 и уже подобранные пороги не придётся менять.
 *
 * Веса подобраны по реальным парам, где ответ известен: пересечение круга
 * друзей оказалось единственным сигналом, который отличает второй аккаунт
 * от обычного друга (0.89 против 0.39 доли меньшего списка).
 */
public class Weights {

    /**
     * Какая доля МЕНЬШЕГО списка друзей совпала — самый информативный сигнал.
     * У альта 9 друзей и 8 из них друзья основы (89%), у обычного друга
     * 28 друзей и совпало только 11 (39%). Симметричные меры (косинус,
     * Жаккар) эту разницу смазывают.
     */
    public double sharedFriends = 0.55;

    /**
     * Синхронность: насколько близко по времени два аккаунта добавляли
     * одних и тех же людей. Самый сильный сигнал "один человек, две вкладки".
     */
    public double coAdd = 0.20;

    /** Близость даты регистрации (номер аккаунта + timecreated). */
    public double creation = 0.10;

    /** Аккаунты состоят в друзьях друг у друга. Слабый сигнал: друзья тоже дружат. */
    public double directFriend = 0.05;

    /** Одинаковый аватар и похожий ник. */
    public double profile = 0.05;

    /**
     * "Залповый" набор друзей: круг собран за один-два вечера.
     * Слабый сигнал сам по себе, но хорошо добивает пару без синхронности.
     */
    public double burst = 0.05;

    // Зарезервировано под будущие сигналы (требуют дополнительных запросов к Steam):
    // public double gameLibrary = 0.10;  // IPlayerService/GetOwnedGames
    // public double groups      = 0.05;  // ISteamUser/GetUserGroupList

    /** Сумма весов активных сигналов — делитель при расчёте итогового скора. */
    public double sum() {
        return sharedFriends + coAdd + creation + directFriend + profile + burst;
    }

    public static Weights defaults() {
        return new Weights();
    }
}
